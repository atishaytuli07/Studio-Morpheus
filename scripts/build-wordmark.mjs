// Dev-only: convert the wordmark to SVG outlines.
//
// Monolog renders its wordmark as vector paths rather than live text — that is
// why no webfont substitution matches it. This does the same for ours: each
// letter becomes its own <path>, so it is crisp at any size, needs no font to
// load before painting, and every glyph can be animated independently.
//
//   node scripts/build-wordmark.mjs
//
// Re-run after changing the text, face or tracking. Output is committed.
import opentype from "opentype.js";
import { readFileSync, writeFileSync } from "fs";

const WEIGHTS = {
  bold: "public/fonts/pangram-sans/PPPangramSans-Bold.otf",
  extrabold: "public/fonts/pangram-sans/PPPangramSans-Extrabold.otf",
};

const TEXT = process.argv[2] || "morpheus";
const FONT = WEIGHTS[process.argv[3] || "bold"] ?? WEIGHTS.bold;
const SIZE = 1000; // work large; the viewBox normalises it
const TRACKING = -0.05; // em, matches the CSS letter-spacing we were using

const font = opentype.parse(readFileSync(FONT).buffer);

let x = 0;
const letters = [];

for (const ch of TEXT) {
  const path = font.getPath(ch, x, 0, SIZE);
  const d = path.toPathData(2);
  const bb = path.getBoundingBox();
  letters.push({ ch, d, x1: bb.x1, x2: bb.x2, y1: bb.y1, y2: bb.y2 });
  x += font.getAdvanceWidth(ch, SIZE) + TRACKING * SIZE;
}

// tight bounding box across every glyph, so the artwork has no dead margin
const x1 = Math.min(...letters.map((l) => l.x1));
const x2 = Math.max(...letters.map((l) => l.x2));
const y1 = Math.min(...letters.map((l) => l.y1));
const y2 = Math.max(...letters.map((l) => l.y2));

const viewBox = [x1, y1, x2 - x1, y2 - y1].map((n) => +n.toFixed(2)).join(" ");

const out = `// GENERATED by scripts/build-wordmark.mjs — do not edit by hand.
// "${TEXT}" outlined from ${FONT.split("/").pop()}.
export const WORDMARK_VIEWBOX = "${viewBox}";

export const WORDMARK_PATHS = [
${letters.map((l) => `  // ${l.ch}\n  "${l.d}",`).join("\n")}
];
`;

writeFileSync("src/components/v2/Hero2/wordmark.js", out);

console.log(`viewBox: ${viewBox}`);
console.log(`glyphs:  ${letters.length}`);
console.log(`size:    ${(out.length / 1024).toFixed(1)} KB`);
